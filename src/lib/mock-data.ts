// Helper to construct dates relative to today
const createDate = (dayOffset: number, hour: number, minute: number = 0) => {
  const d = new Date();
  d.setDate(d.getDate() + dayOffset);
  d.setHours(hour, minute, 0, 0);
  return d.toISOString();
};

